#!/usr/bin/env python3
"""Build a server's master config files from untouched originals and a recipe.

Our changes never live inside the original files. They live in a recipe
(e.g. sahrani-plus/masters.json), and this script rebuilds every master from
the originals plus that recipe, so the same inputs always give the same
output and a new version of an original can be re-merged in one command.

Commands:
    build  RECIPE           write every master and MERGE_REPORT.md
    check  RECIPE           rebuild in memory; fail if a committed master or
                            the report is out of date (used by CI)
    Add --strict to also fail while any conflict is undecided.

Recipe (paths are relative to the recipe file):
    {
      "map_label": "Sahrani Plus (map author)",
      "vanilla_label": "Bohemia vanilla Chernarus",
      "report": "MERGE_REPORT.md",
      "masters": [
        {"type": "merge",            entry-by-entry merge, see merge_entries.py
         "map": "...", "vanilla": "...", "output": "...",
         "add_vanilla": "all" | ["event:AnimalBear", ...],
         "skip_vanilla": [...], "drop_map": {"event:AnimalTREX": "why"},
         "decisions": {"export:AppleTree2": {"keep": "map", "why": "..."}}},

        {"type": "patch",            exact text edits on one original
         "from": "...", "output": "...",
         "edits": [{"find": "...", "replace": "...", "why": "..."}]},

        {"type": "copy",             an original used unchanged
         "from": "...", "output": "...", "why": "..."}
      ]
    }

    Patch "find" text must occur exactly once in the original. Write line
    breaks as \\n; they are matched against the file's own line endings. If an
    updated original no longer contains the text, the build stops and says
    which edit needs a look.

Standard library only (Python 3.8+), runs on Windows too.
Exit codes: 0 ok, 1 check or verification failed, 2 bad input.
"""
from __future__ import annotations

import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import merge_entries  # noqa: E402


def well_formed(name: str, data: bytes) -> str | None:
    try:
        if name.lower().endswith(".xml"):
            ET.fromstring(data)
        elif name.lower().endswith(".json"):
            json.loads(data.decode("utf-8-sig"))
    except (ET.ParseError, ValueError) as e:
        return f"{name} is not well-formed: {e}"
    return None


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:12]


def patch(step: dict, here: Path) -> tuple[bytes, list[str], list[str]]:
    raw = (here / step["from"]).read_bytes()
    bom, text, nl = merge_entries.decode(raw)
    problems: list[str] = []
    r = [f"## {Path(step['output']).name}", "",
         f"Patched copy of `{step['from']}` (sha256 `{sha(raw)}`) → `{step['output']}`.", "",
         "| # | Change | Why |", "|---|---|---|"]
    for n, ed in enumerate(step["edits"], 1):
        find = ed["find"].replace("\n", nl)
        repl = ed["replace"].replace("\n", nl)
        count = text.count(find)
        if count != 1:
            problems.append(f"edit {n} ({ed.get('why', '')}): text found {count} "
                            f"times in {step['from']}, expected once. The original "
                            f"probably changed: update the recipe.")
            continue
        text = text.replace(find, repl)
        summary = ed.get("summary") or (
            "replaced `" + ed["find"].strip().splitlines()[0][:60] + "`")
        r.append(f"| {n} | {summary} | {ed.get('why', '')} |")
    data = (b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8")
    bad = well_formed(step["output"], data)
    if bad:
        problems.append(bad)
    r += ["", f"Master sha256 `{sha(data)}`. Verification: "
              f"{'**FAILED**' if problems else 'passed'}.", ""]
    r += [f"- {p}" for p in problems] + ([""] if problems else [])
    return data, r, problems


def copy(step: dict, here: Path) -> tuple[bytes, list[str], list[str]]:
    data = (here / step["from"]).read_bytes()
    r = [f"## {Path(step['output']).name}", "",
         f"Unchanged copy of `{step['from']}` (sha256 `{sha(data)}`). "
         f"{step.get('why', '')}", ""]
    return data, r, []


def build(recipe_path: Path) -> tuple[dict[Path, bytes], list[str], list[str]]:
    here = recipe_path.parent
    rec = json.loads(recipe_path.read_text(encoding="utf-8"))
    map_label = rec.get("map_label", "map")
    van_label = rec.get("vanilla_label", "vanilla")
    outputs: dict[Path, bytes] = {}
    report = ["# Master build report", "",
              f"Generated by `tools/build_masters.py` from `{recipe_path.name}`. "
              f"Do not edit by hand.", ""]
    problems: list[str] = []
    undecided: list[str] = []
    for step in rec["masters"]:
        kind = step.get("type")
        if kind == "merge":
            res = merge_entries.merge(step, here, map_label, van_label)
            data, r, p = res.output, res.report, res.problems
            undecided += [f"{step['output']}: {k}" for k in res.undecided]
        elif kind == "patch":
            data, r, p = patch(step, here)
        elif kind == "copy":
            data, r, p = copy(step, here)
        else:
            raise SystemExit(f"unknown master type {kind!r}")
        out = here / step["output"]
        if out in outputs:
            raise SystemExit(f"{step['output']} is built twice")
        outputs[out] = data
        report += r
        problems += [f"{step['output']}: {x}" for x in p]
    if undecided:
        report += ["## Waiting on Boss", ""] + [f"- {u}" for u in undecided] + [""]
    outputs[here / rec.get("report", "MERGE_REPORT.md")] = "\n".join(report).encode("utf-8")
    return outputs, problems, undecided


def main(argv: list[str]) -> int:
    if len(argv) < 2 or argv[0] not in ("build", "check"):
        print(__doc__)
        return 2
    recipe = Path(argv[1]).resolve()
    outputs, problems, undecided = build(recipe)
    for p in problems:
        print(f"ERROR {p}")
    for u in undecided:
        print(f"UNDECIDED {u} (map version kept for now)")
    if argv[0] == "build":
        if problems:
            print("Nothing written: fix the problems above first.")
            return 1
        for path, data in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"wrote {len(outputs)} files under {recipe.parent}")
    else:
        stale = [p for p, d in outputs.items() if not p.is_file() or p.read_bytes() != d]
        for p in stale:
            print(f"ERROR {p} is out of date: run 'build' and commit")
        if stale or problems:
            return 1
        print(f"all {len(outputs)} masters are up to date")
    return 1 if ("--strict" in argv and undecided) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
